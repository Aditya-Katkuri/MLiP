def load_listing(dirs):
    rows = []
    for d in dirs:
        for f in hf_tree(DATASET_REPO.format(d)):
            if f["path"].count("/") != 2:
                continue  # .gitattributes
            split, verdict, city, lid = parse_crop_path(f["path"])
            rows.append(dict(dir=d, relpath=f["path"], split=split, verdict=verdict, city=city, label_id=lid,
                             hf_bytes=f["size"], hf_sha256=(f.get("lfs") or {}).get("oid")))
    return pd.DataFrame(rows)


def scan_local(data_root, dirs, workers):
    paths = []
    for d in dirs:
        root = os.path.join(data_root, f"sidewalk-validator-ai-dataset-{d}")
        for dp, dns, fns in os.walk(root):
            dns[:] = [x for x in dns if not x.startswith(".")]
            paths += [(d, os.path.join(dp, fn)) for fn in fns if not fn.startswith(".")]
    t = time.time()
    with cf.ProcessPoolExecutor(max_workers=workers) as ex:
        feats = list(ex.map(image_features, [p for _, p in paths], chunksize=64))
    for (d, p), rec in zip(paths, feats):
        rec["dir"] = d
        rec["relpath"] = os.path.relpath(p, os.path.join(data_root, f"sidewalk-validator-ai-dataset-{d}"))
    print(f"  hashed + decoded {len(feats)} files in {time.time() - t:.0f}s", flush=True)
    return pd.DataFrame(feats).reindex(columns=["dir", "relpath", "path", "bytes", "sha256", "ok", "error", "width",
                                                "height", "mode", "format", "dhash", "mean_luma"])


def near_duplicates(df, hamming):
    """All pairs with dHash Hamming distance <= hamming, chunked brute force (numpy.bitwise_count)."""
    df = df.reset_index(drop=True)
    h = np.array([int(x, 16) for x in df["dhash"]], dtype=np.uint64)
    pairs, B = [], 512
    idx = np.arange(len(h))
    for s in range(0, len(h), B):
        block = h[s:s + B]
        dist = np.bitwise_count(block[:, None] ^ h[None, :])
        ii, jj = np.nonzero((dist <= hamming) & (idx[None, :] > (idx[s:s + B])[:, None]))
        for a, b in zip(ii + s, jj):
            pairs.append((a, b, int(dist[a - s, b])))
    out = []
    for a, b, dd in pairs:
        ra, rb = df.iloc[a], df.iloc[b]
        if ra.dir != rb.dir:
            kind = "cross-class"
        elif ra.split != rb.split:
            kind = "within-class, cross-split"
        else:
            kind = "within-class, same split"
        out.append(dict(kind=kind, hamming=dd, exact=ra.sha256 == rb.sha256,
                        same_city_label=(ra.city, ra.label_id) == (rb.city, rb.label_id),
                        a=f"{ra.dir}/{ra.relpath}", b=f"{rb.dir}/{rb.relpath}",
                        a_verdict=ra.verdict, b_verdict=rb.verdict,
                        verdict_conflict=(ra.dir == rb.dir and ra.verdict != rb.verdict)))
    return pd.DataFrame(out, columns=["kind", "hamming", "exact", "same_city_label", "a", "b",
                                      "a_verdict", "b_verdict", "verdict_conflict"])


def fetch_bytes(url, tries=4):
    """Whole-body GET with retries -- the Project Sidewalk servers drop long responses now and then."""
    for attempt in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=600) as r:
                return r.read()
        except Exception as e:
            if attempt == tries - 1:
                raise
            print(f"  retry {attempt + 1} {url}: {type(e).__name__}", flush=True)
            time.sleep(10 * (attempt + 1))


def label_type_check(listing, pgh_labels, cities):
    cols = ["label_id", "label_type", "severity", "agree_count", "disagree_count"]
    frames = []
    for city in ["pittsburgh", *cities]:
        src = pgh_labels if city == "pittsburgh" and os.path.exists(pgh_labels) else PS_RAW.format(city.replace("_", "-"))
        try:
            raw = pd.read_csv(src if os.path.exists(src) else io.BytesIO(fetch_bytes(src)), usecols=cols)
        except Exception as e:
            print(f"  label check: could not read {src}: {e}", flush=True)
            continue
        m = listing[listing.city == city].merge(raw, on="label_id", how="left")
        m["source"] = src
        frames.append(m)
    if not frames:
        return None, None
    m = pd.concat(frames, ignore_index=True)
    m["label_type"] = m["label_type"].fillna("<not in live API>")
    m["matches_dir"] = m["label_type"] == m["dir"].map(EXPECTED_TYPE)
    ct = pd.crosstab([m.city, m.dir], m.label_type)
    return m, ct


def safetensors_header(path_or_url):
    """Tensor count / parameter count / dtypes from the JSON header only -- no weights loaded.
    Works on a local file or, through two HTTP range reads, on a remote one."""
    if os.path.exists(path_or_url):
        with open(path_or_url, "rb") as f:
            n = struct.unpack("<Q", f.read(8))[0]
            hdr = json.loads(f.read(n))
    else:
        rr = RangeReader(path_or_url)
        n = struct.unpack("<Q", rr.read_at(0, 8))[0]
        hdr = json.loads(rr.read_at(8, n))
    hdr.pop("__metadata__", None)
    params = sum(int(np.prod(v["shape"])) for v in hdr.values())
    dtypes = collections.Counter(v["dtype"] for v in hdr.values())
    return dict(tensors=len(hdr), params=params, dtypes=dict(dtypes))


def model_section(models_root, listing):
    out = {}
    for d in DIRS:
        repo = MODEL_REPO.format(d)
        local = os.path.join(models_root, f"sidewalk-validator-ai-{d}")

        def load(name):
            p = os.path.join(local, name)
            if os.path.exists(p):
                return json.load(open(p))
            return get_json(f"{HF}/{repo}/resolve/main/{name}")

        cfg, pp, ts = load("config.json"), load("preprocessor_config.json"), load("trainer_state.json")
        evals = [h for h in ts["log_history"] if "eval_macro_f1" in h]
        steps_per_epoch = (evals[1]["step"] - evals[0]["step"]) if len(evals) > 1 else None
        # HF Trainer: optimizer steps/epoch = ceil(ceil(N / bs) / accum)  =>  N in (lo, hi]
        implied = None
        if steps_per_epoch:
            implied = [(steps_per_epoch - 1) * GRAD_ACCUM * TRAIN_BS + 1, steps_per_epoch * GRAD_ACCUM * TRAIN_BS]
        published_train = int(((listing.dir == d) & (listing.split == "train")).sum()) if len(listing) else None
        tree = {f["path"]: f for f in hf_tree(repo, "models")}
        st = os.path.join(local, "model.safetensors")
        rec = dict(
            hf_repo=f"{HF}/{repo}", hf_commit=get_json(f"{HF}/api/models/{repo}").get("sha"),
            architecture=cfg.get("architectures"), model_type=cfg.get("model_type"),
            hidden_size=cfg.get("hidden_size"), num_hidden_layers=cfg.get("num_hidden_layers"),
            config_image_size=cfg.get("image_size"), patch_size=cfg.get("patch_size"),
            id2label=cfg.get("id2label"), transformers_version=cfg.get("transformers_version"),
            preprocessor=dict(type=pp.get("image_processor_type"), size=pp.get("size"),
                              crop_size=pp.get("crop_size"), mean=pp.get("image_mean"), std=pp.get("image_std")),
            best_model_checkpoint=ts.get("best_model_checkpoint"), best_val_macro_f1=ts.get("best_metric"),
            epoch_at_checkpoint=ts.get("epoch"), global_step=ts.get("global_step"), max_steps=ts.get("max_steps"),
            num_train_epochs=ts.get("num_train_epochs"),
            val_macro_f1_by_epoch=[round(h["eval_macro_f1"], 4) for h in evals],
            val_loss_by_epoch=[round(h["eval_loss"], 4) for h in evals],
            optimizer_steps_per_epoch=steps_per_epoch, implied_train_images_range=implied,
            published_train_split_images=published_train,
            implied_matches_published=(implied is not None and published_train is not None
                                       and implied[0] <= published_train <= implied[1]),
            weights_sha256=(tree.get("model.safetensors", {}).get("lfs") or {}).get("oid"),
            weights_bytes=tree.get("model.safetensors", {}).get("size"),
            local_files=sorted(os.listdir(local)) if os.path.isdir(local) else None,
        )
        rec["safetensors"] = safetensors_header(st if os.path.exists(st) else f"{HF}/{repo}/resolve/main/model.safetensors")
        if os.path.isdir(local):  # verify whatever has landed locally against the HF listing
            chk = {}
            for name, f in tree.items():
                p = os.path.join(local, name)
                if not os.path.exists(p):
                    chk[name] = "missing"
                elif os.path.getsize(p) != f["size"]:
                    chk[name] = f"size {os.path.getsize(p)} != {f['size']}"
                elif name == "model.safetensors":
                    h = hashlib.sha256()
                    with open(p, "rb") as fh:
                        while blk := fh.read(1 << 24):
                            h.update(blk)
                    chk[name] = "sha256 ok" if h.hexdigest() == rec["weights_sha256"] else "SHA256 MISMATCH"
                else:
                    chk[name] = "size ok"
            rec["local_verification"] = chk
        out[d] = rec
    shas = {d: r["weights_sha256"] for d, r in out.items()}
    return out, dict(distinct_weight_files=len(set(shas.values())), sha256=shas)


def tagger_section():
    out = {}
    for group, archives in TAGGER.items():
        repo = f"projectsidewalk/sidewalk-tagger-ai-{group}"
        base = f"{HF}/datasets/{repo}/resolve/main/"
        for parts in archives:
            key = f"{group}/{parts[-1]}"
            try:
                entries, fetched = list_zip_central_directory([base + p for p in parts])
            except Exception as e:
                out[key] = dict(error=f"{type(e).__name__}: {e}")
                print(f"  tagger {key}: {e}", flush=True)
                continue
            files = [e for e in entries if not e[0].endswith("/")]
            ext = collections.Counter(e[0].rsplit(".", 1)[-1].lower() for e in files)
            csvs = [e[0] for e in files if e[0].endswith(".csv")]
            # crop filenames are <source>-<city>-<label_id>-<LabelType>.png, e.g. gsv-pittsburgh-761-CurbRamp.png
            city = collections.Counter(e[0].split("/")[-1].split("-")[1] for e in files
                                       if e[0].endswith(".png") and e[0].split("/")[-1].count("-") >= 3)
            rec = dict(hf=f"{HF}/datasets/{repo}", parts=parts, entries=len(files), by_extension=dict(ext),
                       by_city=dict(city.most_common()), pittsburgh_images=city.get("pittsburgh", 0),
                       images=sum(n for x, n in ext.items() if x in ("png", "jpg", "jpeg", "webp")),
                       uncompressed_gb=round(sum(e[1] for e in files) / 1e9, 2), csv_members=csvs,
                       central_directory_bytes_fetched=fetched)
            if len(parts) == 1 and csvs:  # single-part archive: read the (small) tag CSVs too
                rr = RangeReader(base + parts[0])
                z = zipfile.ZipFile(io.BufferedReader(_SeekableRange(rr), buffer_size=1 << 20))
                rec["csv"] = {}
                for c in csvs:
                    t = pd.read_csv(io.BytesIO(z.read(c)))
                    tagcols = [x for x in t.columns if set(pd.unique(t[x].dropna())) <= {0, 1}]
                    rec["csv"][c] = dict(rows=len(t), columns=list(t.columns)[:8] + (["..."] if len(t.columns) > 8 else []),
                                         tag_positives={x: int(t[x].sum()) for x in tagcols})
                rec["central_directory_bytes_fetched"] += rr.fetched
            out[key] = rec
            print(f"  tagger {key}: {rec['images']} images, {rec['uncompressed_gb']} GB uncompressed", flush=True)
    return out


def montage(feats, data_root, out_png, per_correct=6, per_incorrect=3, tile=160, seed=0):
    rng = np.random.default_rng(seed)
    rows = []
    for d in DIRS:
        sub = feats[(feats.dir == d) & feats.ok]
        if not len(sub):
            continue
        pick = []
        for v, k in [("correct", per_correct), ("incorrect", per_incorrect)]:
            s = sub[sub.verdict == v]
            pick += [(v, r) for _, r in s.iloc[rng.choice(len(s), min(k, len(s)), replace=False)].iterrows()]
        rows.append((d, pick))
    label_w = 170
    W, H = label_w + tile * (per_correct + per_incorrect), (tile + 18) * len(rows)
    canvas = Image.new("RGB", (W, H), "white")
    draw = ImageDraw.Draw(canvas)
    for ri, (d, pick) in enumerate(rows):
        y = ri * (tile + 18)
        name = f"{d}/\n(== crosswalk bytes)" if d == "curbramp" else f"{d}/"
        draw.text((6, y + tile // 2 - 10), name, fill="black")
        for ci, (v, r) in enumerate(pick):
            im = Image.open(os.path.join(data_root, f"sidewalk-validator-ai-dataset-{d}", r.relpath)).convert("RGB")
            im.thumbnail((tile, tile))
            x = label_w + ci * tile
            canvas.paste(im, (x, y))
            draw.text((x + 2, y + tile + 2), f"{v[:3]} {r.city}", fill="green" if v == "correct" else "red")
    canvas.save(out_png)


def pair_montage(pairs, data_root, out_png, n=10, tile=180):
    sel = pairs[pairs.kind != "within-class, same split"].sort_values("hamming").head(n)
    if not len(sel):
        return 0
    canvas = Image.new("RGB", (tile * 2 + 10, (tile + 30) * len(sel)), "white")
    draw = ImageDraw.Draw(canvas)
    for i, (_, p) in enumerate(sel.iterrows()):
        y = i * (tile + 30)
        for j, key in enumerate(["a", "b"]):
            d, rel = p[key].split("/", 1)
            im = Image.open(os.path.join(data_root, f"sidewalk-validator-ai-dataset-{d}", rel)).convert("RGB")
            im.thumbnail((tile, tile))
            canvas.paste(im, (j * (tile + 10), y))
        draw.text((2, y + tile + 2), f"{p.kind} h={p.hamming} exact={p.exact}", fill="black")
        draw.text((2, y + tile + 14), f"{p.a.split('/')[-1]} | {p.b.split('/')[-1]}", fill="black")
    canvas.save(out_png)
    return len(sel)


