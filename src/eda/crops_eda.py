# ----------------------------------------------------------------------------- helpers
def get_json(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
        return json.load(r)


def hf_tree(repo, kind="datasets"):
    """Full recursive file listing of a HF repo, following pagination."""
    out, url = [], f"{HF}/api/{kind}/{repo}/tree/main?recursive=true"
    while url:
        with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=120) as r:
            out += json.load(r)
            link = r.headers.get("Link") or ""
        url = link.split(";")[0].strip("<> ") if 'rel="next"' in link else None
    return [x for x in out if x["type"] == "file"]


def parse_crop_path(relpath):
    """train/correct/<city>_<label_id>.webp -> (split, verdict, city, label_id)"""
    split, verdict, fn = relpath.split("/")
    city, lid = fn.rsplit(".", 1)[0].rsplit("_", 1)
    return split, verdict, city, int(lid)


def image_features(path):
    """sha256 + full decode + 64-bit dHash for one file. Runs in a worker process."""
    with open(path, "rb") as f:
        data = f.read()
    rec = dict(path=path, bytes=len(data), sha256=hashlib.sha256(data).hexdigest())
    try:
        im = Image.open(io.BytesIO(data))
        fmt = im.format
        im.load()
        rec.update(width=im.width, height=im.height, mode=im.mode, format=fmt, ok=True)
        g = np.asarray(im.convert("L").resize((9, 8), Image.Resampling.LANCZOS), dtype=np.int16)
        bits = (g[:, 1:] > g[:, :-1]).flatten()
        rec["dhash"] = format(int(np.packbits(bits).view(">u8")[0]), "016x")
        rec["mean_luma"] = round(float(np.asarray(im.convert("L")).mean()), 2)
    except Exception as e:  # corrupt / undecodable
        rec.update(ok=False, error=f"{type(e).__name__}: {str(e)[:200]}")
    return rec


def jsonable(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    return str(o)


def crosstab_records(ct):
    """DataFrame crosstab -> {row: {col: n}} with flattened string column names."""
    ct = ct.copy()
    ct.columns = ["/".join(map(str, c)) if isinstance(c, tuple) else str(c) for c in ct.columns]
    return {str(k): {c: int(v) for c, v in row.items()} for k, row in ct.iterrows()}


# ----------------------------------------------------------------------------- HTTP range zip listing
class RangeReader:
    """Random access to a remote file through HTTP Range requests; counts bytes fetched."""

    def __init__(self, url):
        req = urllib.request.Request(url, method="HEAD", headers=UA)
        with urllib.request.urlopen(req, timeout=120) as r:
            self.url, self.size = r.url, int(r.headers["Content-Length"])
        self.fetched = 0

    def read_at(self, start, n):
        end = min(start + n, self.size) - 1
        if end < start:
            return b""
        req = urllib.request.Request(self.url, headers={**UA, "Range": f"bytes={start}-{end}"})
        with urllib.request.urlopen(req, timeout=300) as r:
            d = r.read()
        self.fetched += len(d)
        return d


class _SeekableRange(io.RawIOBase):
    def __init__(self, rr):
        self.rr, self.pos = rr, 0

    def readable(self):
        return True

    def seekable(self):
        return True

    def tell(self):
        return self.pos

    def seek(self, off, whence=0):
        self.pos = off if whence == 0 else self.pos + off if whence == 1 else self.rr.size + off
        return self.pos

    def readinto(self, b):
        d = self.rr.read_at(self.pos, len(b))
        b[:len(d)] = d
        self.pos += len(d)
        return len(d)


def list_zip_central_directory(part_urls):
    """Parse a (possibly split, possibly Zip64) archive's central directory from its last part.

    Returns (entries, bytes_fetched) where entries = [(name, uncompressed, compressed)].
    Split archives (.z01, .z02, ..., .zip) number their disks in that order."""
    parts = [RangeReader(u) for u in part_urls]
    last = parts[-1]
    tail_start = max(0, last.size - 70000)
    tail = last.read_at(tail_start, last.size - tail_start)
    i = tail.rfind(b"PK\x05\x06")
    if i < 0:
        raise ValueError("no end-of-central-directory record")
    _, _, cd_disk, _, total, cd_size, cd_off, _ = struct.unpack("<4sHHHHIIH", tail[i:i + 22])
    if 0xFFFF in (cd_disk, total) or 0xFFFFFFFF in (cd_size, cd_off):
        loc = tail[i - 20:i]
        if loc[:4] != b"PK\x06\x07":
            raise ValueError("zip64 locator missing")
        z64_disk, z64_off, _ = struct.unpack("<IQI", loc[4:])
        rec = parts[z64_disk].read_at(z64_off, 56)
        (_, _, _, _, _, cd_disk, _, total, cd_size, cd_off) = struct.unpack("<4sQHHIIQQQQ", rec)
    cd, disk, off = b"", cd_disk, cd_off
    while len(cd) < cd_size:  # the central directory may itself span parts
        chunk = parts[disk].read_at(off, cd_size - len(cd))
        cd += chunk
        disk, off = disk + 1, 0
    entries, p = [], 0
    while p + 46 <= len(cd) and cd[p:p + 4] == b"PK\x01\x02":
        h = struct.unpack("<4sHHHHHHIIIHHHHHII", cd[p:p + 46])
        csize, usize, fnlen, extlen, cmtlen = h[8], h[9], h[10], h[11], h[12]
        name = cd[p + 46:p + 46 + fnlen].decode("utf-8", "replace")
        extra = cd[p + 46 + fnlen:p + 46 + fnlen + extlen]
        if 0xFFFFFFFF in (usize, csize):  # zip64 extended information extra field
            q = 0
            while q + 4 <= len(extra):
                hid, hlen = struct.unpack("<HH", extra[q:q + 4])
                if hid == 0x0001:
                    vals, r = list(struct.unpack(f"<{hlen // 8}Q", extra[q + 4:q + 4 + 8 * (hlen // 8)])), 0
                    if usize == 0xFFFFFFFF:
                        usize, r = vals[r], r + 1
                    if csize == 0xFFFFFFFF:
                        csize = vals[r]
                    break
                q += 4 + hlen
        entries.append((name, usize, csize))
        p += 46 + fnlen + extlen + cmtlen
    if len(entries) != total:
        print(f"    warning: parsed {len(entries)} central-directory entries, EOCD says {total}", flush=True)
    return entries, sum(pp.fetched for pp in parts)


