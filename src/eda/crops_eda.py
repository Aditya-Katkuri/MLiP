#!/usr/bin/env python3
"""EDA of Project Sidewalk's validator-AI crop datasets and the validator models trained on them.

What it establishes (every number lands in <out>/summary.json and <out>/tables/):
  1. integrity  -- local mirror vs the Hugging Face listing: file count, size, sha256 per image
  2. decode     -- every image opened with PIL: size, mode, corrupt files
  3. tables     -- dir x split x verdict, class x city, Pittsburgh counts, exact duplicates
  4. near-dups  -- 64-bit dHash, Hamming <= --hamming, within and across splits and classes
  5. label-type check -- crop filenames are <city>_<label_id>; joining label_id back to that
                  city's rawLabels says which label type a directory really holds
  6. models     -- config / preprocessor / trainer_state / safetensors header of the five
                  validator models, and the train-set size each trainer_state implies
  7. tagger     -- sidewalk-tagger-ai zips, listed through HTTP range reads of their central
                  directory (a few hundred KB each); nothing is downloaded
  8. montage    -- correct / incorrect samples per directory, for eyeballing

The crop datasets were generated by github.com/ProjectSidewalk/sidewalk-validator-ai
(data_generation.py -> split_data.py -> fine_tune_classifier.py).

usage:
  python src/eda/crops_eda.py
  python src/eda/crops_eda.py --dirs obstacle --skip-models --skip-tagger --out /tmp/x
"""
